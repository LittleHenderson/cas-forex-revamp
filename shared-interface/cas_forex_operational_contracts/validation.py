def _resolve(name: str, ns: str, locations: dict[str, list[str]]) -> str | None:
    choices=locations.get(name,[])
    return ns if ns in choices else choices[0] if choices else None

def _before(a: dict[str, Any], b: dict[str, Any], field: str) -> None:
    require(utc(a["utc"])<=utc(b["utc"]) and a["boottime_ns"]<=b["boottime_ns"],"TIME_ORDER",field)

def _unique(values: list[Any], field: str) -> None:
    keys=[canonical_bytes(x,limit=MAX_OBJECT) for x in values]
    require(len(keys)==len(set(keys)),"DUPLICATE",field)

class _Checker:
    def __init__(self, extension: SelectedShapeValidator | None, limits: ValidationLimits | None) -> None:
        self.extension=extension
        self.limits=limits or ValidationLimits()
        require(self.limits.stream_bytes is None or (type(self.limits.stream_bytes) is int and
                0<self.limits.stream_bytes<=524288),"PARSER_LIMIT")

    def shape(self, ns: str, name: str, value: Any, depth: int=0) -> None:
        require(depth<=MAX_DEPTH,"SCHEMA_DEPTH")
        require(ns in CATALOG and name in CATALOG[ns],"UNKNOWN_RECORD")
        fields=CATALOG[ns][name]
        require(type(value) is dict and set(value)==set(fields),"EXACT_FIELDS",name)
        for key,expr in fields.items():
            self.value(expr,value[key],ns,name,key,value,depth+1)
        self.local(ns,name,value)

    def value(self, expr: str, value: Any, ns: str, record: str, field: str,
              parent: dict[str,Any], depth: int) -> None:
        require(depth<=MAX_DEPTH,"SCHEMA_DEPTH",record+"."+field)
        expr=EXPRESSION_ALIASES.get(expr,expr)
        loc=_resolve(expr,ns,TYPE_LOCATIONS)
        if loc is not None:
            self.shape(loc,expr,value,depth); return
        loc=_resolve(expr,ns,ENUM_LOCATIONS)
        if loc is not None:
            require(type(value) is str and value in ENUMS[loc][expr],"ENUM",field); return
        if expr.startswith("Nullable<") and expr.endswith(">"):
            if value is not None: self.value(expr[9:-1],value,ns,record,field,parent,depth+1)
            return
        match=re.fullmatch(r"array<(.+)>\[([0-9]+),([0-9]+)\]",expr)
        if match:
            require(type(value) is list and int(match[2])<=len(value)<=int(match[3]),"ARRAY_LENGTH",field)
            for item in value: self.value(match[1],item,ns,record,field,parent,depth+1)
            return
        if expr.startswith("ObjectRef:"):
            self.shape("method","ObjectRef",value,depth)
            require(value["artifact_kind"]==expr.split(":",1)[1],"ARTIFACT_KIND",field); return
        if expr.startswith("literal:"):
            require(type(value) is str and value==expr[8:],"LITERAL",field); return
        if expr.startswith("literal-integer:"):
            require(type(value) is int and value==int(expr[16:]),"LITERAL",field); return
        if expr.startswith("literal-bool:"):
            require(type(value) is bool and value==(expr[13:]=="true"),"LITERAL",field); return
        if expr in ("exact:fixed_unsupported_routes","exact:method.fixed_unsupported_routes"):
            require(type(value) is list and value==UNSUPPORTED_ROUTES,"UNSUPPORTED_ROUTES",field); return
