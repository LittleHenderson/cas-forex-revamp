        bounds={"UInt":(0,2**63-1),"PositiveInt":(1,2**63-1),"SignedInt":(-(2**63),2**63-1)}
        match=re.fullmatch(r"Int\[(-?[0-9]+),(-?[0-9]+)\]",expr)
